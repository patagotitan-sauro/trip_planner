"""Generate the Claude and Copilot skill and agent files from .agents/ (the single source)."""

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / ".agents"
NOTICE = "<!-- Generated by scripts/sync_agents.py from .agents/; edit the source. -->"
# Source agents use generic tool names; each tool spells them differently.
TOOLS = {
    "claude": {"read": "Read", "search": "Grep, Glob"},
    "copilot": {"read": "'read'", "search": "'search'"},
}


def split_frontmatter(text: str) -> tuple[dict[str, str], str]:
    _, header, body = text.split("---\n", 2)
    fields = dict(line.split(": ", 1) for line in header.strip().splitlines())
    return fields, body.lstrip("\n")


def render(header: list[str], body: str) -> str:
    return "\n".join(["---", *header, "---", NOTICE, "", body])


def render_skill(fields: dict[str, str], body: str) -> str:
    return render([f"name: {fields['name']}", f"description: {fields['description']}"], body)


def render_agent(fields: dict[str, str], body: str, target: str) -> str:
    names = [name.strip() for name in fields["tools"].split(",")]
    tools = ", ".join(TOOLS[target][name] for name in names)
    tools_line = f"tools: [{tools}]" if target == "copilot" else f"tools: {tools}"
    header = [f"name: {fields['name']}", f"description: {fields['description']}", tools_line]
    return render(header, body)


def build_outputs() -> dict[Path, str]:
    outputs: dict[Path, str] = {}
    for path in sorted((SOURCE / "skills").glob("*/SKILL.md")):
        fields, body = split_frontmatter(path.read_text(encoding="utf-8"))
        text = render_skill(fields, body)
        for tool_dir in (".claude", ".github"):
            outputs[ROOT / tool_dir / "skills" / path.parent.name / "SKILL.md"] = text
    for path in sorted((SOURCE / "agents").glob("*.md")):
        fields, body = split_frontmatter(path.read_text(encoding="utf-8"))
        outputs[ROOT / ".claude" / "agents" / path.name] = render_agent(fields, body, "claude")
        github_name = f"{path.stem}.agent.md"
        outputs[ROOT / ".github" / "agents" / github_name] = render_agent(fields, body, "copilot")
    return outputs


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if generated files are stale")
    args = parser.parse_args(argv)

    outputs = build_outputs()
    stale = [
        path
        for path, text in outputs.items()
        if not path.exists() or path.read_text(encoding="utf-8") != text
    ]
    if args.check:
        for path in stale:
            print(f"out of date: {path.relative_to(ROOT)}")
        return 1 if stale else 0

    for path in stale:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(outputs[path], encoding="utf-8")
        print(f"wrote {path.relative_to(ROOT)}")
    print(f"{len(outputs)} files in sync ({len(stale)} updated).")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
